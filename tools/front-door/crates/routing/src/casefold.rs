pub(crate) fn is_printable(character: char) -> bool {
    let codepoint = u32::from(character);
    NONPRINTABLE_RANGES
        .binary_search_by(|(start, end)| {
            if codepoint < *start {
                std::cmp::Ordering::Greater
            } else if codepoint > *end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_err()
}

