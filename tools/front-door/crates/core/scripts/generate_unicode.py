#!/usr/bin/env python3
"""Generate core's single Unicode property table with CPython Unicode 16.0.0."""
from pathlib import Path
import unicodedata

if unicodedata.unidata_version != "16.0.0":
    raise SystemExit("Unicode 16.0.0 is required; refusing to change the contract")


def properties(code):
    c = chr(code)
    return (int(c.isprintable()) | int(c.isalpha()) << 1 | int(c.isdigit()) << 2
            | int(c.isdecimal()) << 3 | int(c.isnumeric()) << 4 | int(c.isspace()) << 5)


ranges = []
start, previous = 0, properties(0)
for code in range(1, 0x110001):
    flags = properties(code) if code < 0x110000 else -1
    if flags != previous:
        if previous:
            ranges.append((start, code - 1, previous))
        start, previous = code, flags
out = ["// Generated by scripts/generate_unicode.py; CPython Unicode 16.0.0.",
       "// Bits: printable, alpha, digit, decimal, numeric, whitespace.",
       "#[rustfmt::skip]", "pub(super) const PROPERTIES: &[(u32, u32, u8)] = &["]
out += [f"    (0x{a:x}, 0x{b:x}, {flags})," for a, b, flags in ranges]
out += ["];"]
Path(__file__).resolve().parents[1].joinpath("src/py/unicode_data.rs").write_text("\n".join(out) + "\n")
