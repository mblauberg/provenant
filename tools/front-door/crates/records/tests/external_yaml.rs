#[test]
fn every_tracked_skill_frontmatter_and_agent_sidecar_uses_the_subset() {
    assert_eq!(
        FIXTURES.len(),
        36,
        "update this fixture inventory with tracked YAML files"
    );
    for (path, source) in FIXTURES {
        let result = if path.ends_with("/SKILL.md") {
            parse_frontmatter(source)
        } else {
            parse_sidecar(source)
        };
        assert!(result.is_ok(), "{path}: {:?}", result.err());
    }
}
