    fn lane_local(row: &AttemptRecord) -> Result<Value, String> {
        lane_with_facts(row, &[])
    }

    fn lane_local_with_waits(
        row: &AttemptRecord,
        waits: &[provenant_run::LaneWait],
    ) -> Result<Value, String> {
        lane_with_facts(row, waits)
    }

    /// Assemble the same wire row as the owner from deterministic synthetic
    /// observations. The owner and generator share the loaded-facts projection
    /// seam; no ambient fixture paths are read.
    fn lane_with_facts(
        row: &AttemptRecord,
        waits: &[provenant_run::LaneWait],
    ) -> Result<Value, String> {
        use provenant_records::wire::{LanePresence, LaneProjectionFacts};

        let wait = waits.iter().find(|wait| wait.attempt_id == row.attempt_id);
        let presence = matches!(&row.state, provenant_run::AttemptState::Running { .. })
            .then_some(LanePresence::Unknown);
        let mut projected = provenant_cli::run::project_lane_with_loaded_facts(
            row,
            wait,
            Path::new("/fixture"),
            None,
            true,
            true,
            LaneProjectionFacts {
                presence,
                payload_evicted: false,
                ..Default::default()
            },
        );
        provenant_cli::run::normalise_lane_wait_reason(&mut projected);
        serde_json::to_value(projected).map_err(|error| format!("lane projection: {error}"))
    }

    fn output_lane(
        row: &AttemptRecord,
        payload_evicted: bool,
    ) -> Result<provenant_records::wire::LaneRow, String> {
        use provenant_records::wire::{LanePresence, LaneProjectionFacts};
        let presence = matches!(&row.state, provenant_run::AttemptState::Running { .. })
            .then_some(LanePresence::Live);
        let now = provenant_core::WallTime::from_micros(1_800_000_000_000_000)
            .map_err(|error| format!("synthetic output observation time: {error}"))?;
        Ok(provenant_cli::run::project_lane_with_loaded_facts(
            row,
            None,
            Path::new("/fixture"),
            Some(now),
            true,
            true,
            LaneProjectionFacts {
                presence,
                payload_evicted,
                ..Default::default()
            },
        ))
    }

    fn project_output(
        data: &mut Value,
        row: &AttemptRecord,
        payload_evicted: bool,
    ) -> Result<(), String> {
        use provenant_cli::console::projection as p;
        let lane = output_lane(row, payload_evicted)?;
        p::output_lane_fields(data, &lane, row.attempt_id);
        Ok(())
    }

    fn output_envelope(data: Value, row: &AttemptRecord) -> Result<Value, String> {
        use provenant_cli::console::projection as p;
        let target = provenant_cli::Target::parse(&row.key.to_string())
            .map_err(|error| format!("synthetic output target: {error}"))?;
        let mut envelope = CommandResult::new("output", Outcome::Ok, data);
        envelope.next = p::output_next_step(&envelope.data, Some(&target))
            .into_iter()
            .collect();
        serde_json::to_value(envelope).map_err(|error| format!("output envelope: {error}"))
    }

    fn output_result_artifact(
        record: &mut AttemptRecord,
        bytes: u64,
        complete: bool,
    ) -> Result<(), String> {
        let id = record.attempt_id;
        record.result = Some(
            serde_json::from_value(json!({
                "path":{"encoding":"utf8","path":format!("attempts/{id}/result.txt")},
                "digest":"sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb",
                "bytes":bytes,
                "complete":complete,
                "redacted":false
            }))
            .map_err(|error| format!("synthetic output artifact: {error}"))?,
        );
        Ok(())
    }

    /// An admitted operation stored beside the fixture attempt.
    fn operation(id: &str, parent: Option<&str>) -> Result<Value, String> {
        let record: provenant_run::OperationRecord = serde_json::from_value(json!({
            "schema_version":1,
            "project_id":"01010101010101010101010101010101",
            "actor_id":"02020202020202020202020202020202",
            "operation_id":id,
            "kind":"dispatch",
            "request_digest":provenant_core::Digest::from_bytes([7;32]),
            "parent_attempt":parent,
            "state":"accepted"
        }))
        .map_err(|error| format!("synthetic operation: {error}"))?;
        serde_json::to_value(record).map_err(|error| format!("operation projection: {error}"))
    }

    fn lane_wait(id: &str) -> Result<provenant_run::LaneWait, String> {
        let wait: provenant_run::LaneWait = serde_json::from_value(json!({
            "attempt_id":id,"lane_class":"read_only",
            "waiting_for":{"kind":"launch_preparation"}
        }))
        .map_err(|error| format!("synthetic lane wait: {error}"))?;
        Ok(wait)
    }

