//! Generate the macOS app's replay fixtures from the CLI's real projections.
//!
//! This is a development tool, not an installed binary. Every fixture value is
//! synthetic: fixed ids, fixed paths under `/fixture`, fixed timestamps. The
//! generator builds one synthetic set of loaded values and passes it to the
//! same pure projection functions (`provenant_cli::console::projection`) that
//! the owner commands call; the envelope is the real `CommandResult` wire
//! type. No console envelope is written here by hand. A change to any of
//! those projections — or to the wire types they serialise — changes the
//! generated bytes, and `scripts/check-swift-fixtures` fails until the
//! fixtures are regenerated and the Swift decoders are updated.
//!
//! Usage, from the repository root:
//!   cd tools/front-door && cargo run -p provenant-cli --bin generate-swift-fixtures -- --out ../../apps/quota-menubar/Tests/ProvenantTestSupport/Fixtures
//!   cd tools/front-door && cargo run -p provenant-cli --bin generate-swift-fixtures -- --check ../../apps/quota-menubar/Tests/ProvenantTestSupport/Fixtures

use std::path::{Path, PathBuf};

use provenant_records::{CommandResult, Outcome};
use provenant_workflow::session::checkpoint_summary_line;
use serde_json::{Value, json};

/// Relative to this crate's manifest, so the default works from any working directory.
const DEFAULT_FIXTURES: &str = "../../../../apps/quota-menubar/Tests/ProvenantTestSupport/Fixtures";

fn default_fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(DEFAULT_FIXTURES)
}

fn envelope(command: &str, data: Value) -> Result<Value, String> {
    serde_json::to_value(CommandResult::new(command, Outcome::Ok, data))
        .map_err(|error| format!("command envelope: {error}"))
}

fn error_envelope(command: &str, code: &str, message: &str, repair: &str) -> Result<Value, String> {
    let result = CommandResult {
        schema_version: provenant_records::wire::ENVELOPE_VERSION,
        command: command.to_owned(),
        status: Outcome::Error,
        data: Value::Null,
        error: Some(provenant_records::CommandError::new(
            code, message, None, repair,
        )),
        warnings: Vec::new(),
        next: Vec::new(),
    };
    serde_json::to_value(result).map_err(|error| format!("error envelope: {error}"))
}

fn write(directory: &Path, name: &str, value: &Value) -> Result<PathBuf, String> {
    let path = directory.join(format!("{name}.json"));
    let mut text =
        serde_json::to_string_pretty(value).map_err(|error| format!("{name}: {error}"))?;
    text.push('\n');
    std::fs::write(&path, text).map_err(|error| format!("{}: {error}", path.display()))?;
    Ok(path)
}

fn main() -> Result<(), String> {
    let mut out: Option<PathBuf> = None;
    let mut check: Option<PathBuf> = None;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--out" => out = args.next().map(PathBuf::from),
            "--check" => check = args.next().map(PathBuf::from),
            other => return Err(format!("unknown argument: {other}")),
        }
    }
    let directory = out
        .or_else(|| check.clone())
        .unwrap_or_else(default_fixtures);

    let fixtures = fixtures::all()?;
    if let Some(committed) = check {
        let mut drifted = Vec::new();
        for (name, value) in &fixtures {
            let mut expected =
                serde_json::to_string_pretty(value).map_err(|error| format!("{name}: {error}"))?;
            expected.push('\n');
            let path = committed.join(format!("{name}.json"));
            match std::fs::read_to_string(&path) {
                Ok(actual) if actual == expected => {}
                _ => drifted.push((*name).to_owned()),
            }
        }
        if !drifted.is_empty() {
            return Err(format!(
                "Swift replay fixtures are stale: {}. Regenerate with: cd tools/front-door && cargo run -p provenant-cli --bin generate-swift-fixtures -- --out ../../apps/quota-menubar/Tests/ProvenantTestSupport/Fixtures",
                drifted.join(", ")
            ));
        }
        return Ok(());
    }

    std::fs::create_dir_all(&directory)
        .map_err(|error| format!("{}: {error}", directory.display()))?;
    for (name, value) in &fixtures {
        write(&directory, name, value)?;
    }
    Ok(())
}

