    #[test]
    fn committed_fixtures_match_every_projected_byte() {
        for (name, value) in fixtures::all().expect("synthetic fixtures") {
            let mut expected = serde_json::to_string_pretty(&value).expect("fixture JSON");
            expected.push('\n');
            let actual = std::fs::read_to_string(default_fixtures().join(format!("{name}.json")))
                .expect("committed fixture");
            assert_eq!(actual, expected, "fixture {name} must match its projection");
        }
    }

    #[test]
    fn committed_operation_metadata_omits_absent_parents_and_keeps_present_ones() {
        let mut present = 0;
        let mut absent = 0;
        for (name, rows) in [
            ("console-board", "lanes"),
            ("console-tree", "nodes"),
            ("console-tree-conflicts", "nodes"),
            ("console-tree-subtree", "nodes"),
            ("console-tree-limited", "nodes"),
        ] {
            let bytes = std::fs::read(default_fixtures().join(format!("{name}.json")))
                .expect("committed fixture");
            let fixture: serde_json::Value = serde_json::from_slice(&bytes).expect("fixture JSON");
            for row in fixture["data"][rows].as_array().expect("fixture rows") {
                let operation = row["metadata"]["operation"]
                    .as_object()
                    .expect("operation metadata");
                match operation.get("parent_attempt") {
                    None => absent += 1,
                    Some(value) => {
                        assert!(value.is_string(), "present parent must be an attempt ID");
                        present += 1;
                    }
                }
            }
        }
        assert!(absent > 0 && present > 0, "cover both parent cases");
    }

    #[test]
    fn synthetic_overview_lanes_share_valid_attempt_ids_with_tree() {
        let generated = fixtures::console().expect("synthetic console fixtures");
        let overview = &generated
            .iter()
            .find(|(name, _)| *name == "console-overview-active")
            .expect("overview fixture")
            .1;
        let tree = &generated
            .iter()
            .find(|(name, _)| *name == "console-tree")
            .expect("tree fixture")
            .1;
        let lanes = overview["data"]["lanes"]
            .as_array()
            .expect("overview lanes");
        let nodes = tree["data"]["nodes"].as_array().expect("tree nodes");
        assert!(!lanes.is_empty());
        for lane in lanes {
            let id = lane["attempt_id"].as_str().expect("attempt ID");
            provenant_core::AttemptId::parse(id).expect("valid attempt ID");
            assert!(
                nodes.iter().any(|node| node["lane_id"]["attempt_id"] == id
                    && node["lane_id"]["key"] == lane["key"])
            );
        }
    }

    #[test]
    fn synthetic_tree_edges_reference_valid_present_parents_and_children() {
        let generated = fixtures::console().expect("synthetic console fixtures");
        let (_, tree) = generated
            .iter()
            .find(|(name, _)| *name == "console-tree")
            .expect("tree fixture");
        let nodes = tree["data"]["nodes"].as_array().expect("tree nodes");
        let edges = tree["data"]["edges"].as_array().expect("tree edges");
        assert!(!edges.is_empty());
        for edge in edges {
            let parent = edge["parent_attempt"].as_str().expect("parent ID");
            provenant_core::AttemptId::parse(parent).expect("valid parent ID");
            assert_eq!(edge["parent_status"], "present");
            let node = nodes
                .iter()
                .find(|node| node["lane_id"]["attempt_id"] == parent)
                .expect("parent node");
            assert!(
                node["children"]
                    .as_array()
                    .expect("children")
                    .iter()
                    .any(|child| child["attempt_id"] == edge["child_attempt"]
                        && child["kind"] == edge["kind"])
            );
        }
    }

