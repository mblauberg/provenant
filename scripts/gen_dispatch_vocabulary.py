#!/usr/bin/env python3
"""Generate the implemented-adapter vocabulary from `dispatch_registry`.

The product-owned `dispatch_registry` in config/adapter-compatibility.yaml is
the one owner. This writes the Python and TypeScript constants derived from it;
`--check` exits non-zero when either generated file is stale.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "config" / "adapter-compatibility.yaml"
PY_OUT = ROOT / "skills" / "orchestrate" / "scripts" / "adapters" / "dispatch_vocabulary.py"
TS_OUT = ROOT / "runtime" / "fabric" / "src" / "dispatch-vocabulary.ts"
NOTICE = "Generated by scripts/gen_dispatch_vocabulary.py from dispatch_registry in config/adapter-compatibility.yaml. Do not edit."


def implemented() -> list[str]:
    registry = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))["dispatch_registry"]
    return sorted(name for name, entry in registry.items() if entry["dispatch"] == "implemented")


def render(names: list[str]) -> dict[Path, str]:
    quoted = ", ".join(f'"{name}"' for name in names)
    return {
        PY_OUT: f'"""{NOTICE}"""\n\nIMPLEMENTED = ({quoted})\n',
        TS_OUT: f"// {NOTICE}\nexport const DISPATCH_ADAPTERS = [{quoted}] as const;\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a generated file is stale")
    check = parser.parse_args().check
    stale = []
    for path, text in render(implemented()).items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path)
        if not check:
            path.write_text(text, encoding="utf-8")
    for path in stale:
        print(f"{'stale' if check else 'wrote'}: {path.relative_to(ROOT)}", file=sys.stderr)
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
